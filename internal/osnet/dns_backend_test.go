func TestDetectBackend(t *testing.T) {
	stub := []byte("# This is /run/systemd/resolve/stub-resolv.conf\nnameserver 127.0.0.53\noptions edns0 trust-ad\n")
	cases := []struct {
		name string
		env  dnsEnv
		want DNSBackend
	}{
		{"resolved stub link", dnsEnv{resolvConfLink: "../run/systemd/resolve/stub-resolv.conf", hasResolvectl: true}, BackendResolved},
		{"resolved stub content", dnsEnv{resolvConf: stub, hasResolvectl: true}, BackendResolved},
		{"nss-resolve", dnsEnv{resolvConf: []byte("nameserver 192.168.1.1\n"), hasResolvectl: true, nsswitch: []byte("hosts: files resolve [!UNAVAIL=return] dns\n")}, BackendResolved},
		{"resolvectl unused", dnsEnv{resolvConf: []byte("nameserver 192.168.1.1\n"), hasResolvectl: true, nsswitch: []byte("hosts: files dns # resolve\n")}, BackendFile},
		{"stub without resolvectl", dnsEnv{resolvConf: stub}, BackendFile},
		{"debian resolvconf", dnsEnv{resolvConfLink: "/run/resolvconf/resolv.conf", hasResolvconf: true}, BackendResolvconf},
		{"openresolv", dnsEnv{resolvConf: []byte("# Generated by resolvconf\nnameserver 10.0.0.1\n"), hasResolvconf: true}, BackendResolvconf},
		{"networkmanager", dnsEnv{resolvConf: []byte("# Generated by NetworkManager\nnameserver 10.0.0.1\n")}, BackendNetworkManager},
		{"plain", dnsEnv{resolvConf: []byte("nameserver 10.0.0.1\n")}, BackendFile},
	}
	for _, c := range cases {
		if got := detectBackend(c.env); got != c.want {
			t.Errorf("%s: %s, want %s", c.name, got, c.want)
		}
	}
}

func TestManagedResolvConf(t *testing.T) {
	orig := []byte("# from DHCP\nnameserver 192.168.1.1\nnameserver 100.80.255.254\nnameserver 1.1.1.1\nnameserver 8.8.8.8\nsearch home.arpa\noptions rotate timeout:2\n")
	out := managedResolvConf(orig, testMagic.Server, []string{"openscale.internal"})
	rc := parseResolvConfFile(out)
	if !rc.managed {
		t.Fatal("marker missing")
	}
	want := []netip.Addr{testMagic.Server, netip.MustParseAddr("192.168.1.1"), netip.MustParseAddr("1.1.1.1")}
	if !slices.Equal(rc.nameservers, want) {
		t.Fatalf("nameservers %v", rc.nameservers)
	}
	if !slices.Equal(rc.search, []string{"openscale.internal", "home.arpa"}) {
		t.Fatalf("search %v", rc.search)
	}
	if slices.Contains(rc.options, "rotate") || !slices.Contains(rc.options, "timeout:2") {
		t.Fatalf("options %v", rc.options)
	}
	// Rewriting its own output changes nothing.
	if again := managedResolvConf(out, testMagic.Server, []string{"openscale.internal"}); string(again) != string(out) {
		t.Fatalf("not stable:\n%s\n%s", out, again)
	}
}

func TestResolvedLinkPlan(t *testing.T) {
	n := NetworkDNS{
		Split:   []SplitDomain{{Domain: "ev.lan", Nameservers: []netip.Addr{netip.MustParseAddr("100.80.0.5")}}},
		Search:  []string{"openscale.internal", "ev.lan"},
		Overlay: testOverlay,
	}
	plan := resolvedLinkPlan(testMagic, n)
	if !slices.Equal(plan.servers, []string{"100.80.255.254"}) {
		t.Fatalf("servers %v: MagicDNS must be the link's only server", plan.servers)
	}
	for _, d := range []string{"openscale.internal", "ev.lan", "~80.100.in-addr.arpa"} {
		if !slices.Contains(plan.domains, d) {
			t.Errorf("domains %v lack %s", plan.domains, d)
		}
	}
	if slices.Contains(plan.domains, "~.") || slices.Contains(plan.domains, "~openscale.internal") {
		t.Fatalf("domains %v", plan.domains)
	}
	n.Nameservers = []netip.Addr{netip.MustParseAddr("100.80.0.6")}
	if !slices.Contains(resolvedLinkPlan(testMagic, n).domains, "~.") {
		t.Fatal("network-wide resolvers need ~.")
	}
	n.Nameservers = nil
	n.ExitActive = true
	if !slices.Contains(resolvedLinkPlan(testMagic, n).domains, "~.") {
		t.Fatal("an exit node needs ~.")
	}
	got := parseResolvectlList([]byte("Link 7 (OpenScale): ~openscale.internal ~80.100.in-addr.arpa\n"))
	if !sameSet(got, []string{"~80.100.in-addr.arpa", "~openscale.internal"}) {
		t.Fatalf("parsed %v", got)
	}
}

func TestNetworkDNSSearchValidation(t *testing.T) {
	split := []SplitDomain{{Domain: "ev.lan", Nameservers: []netip.Addr{netip.MustParseAddr("100.80.0.5")}}}
	ok := NetworkDNS{Split: split, Search: []string{"openscale.internal", "ev.lan"}, Overlay: testOverlay}
	if err := ok.validate(testMagic); err != nil {
		t.Fatal(err)
	}
	for _, s := range []string{"example.com", "lan"} {
		bad := NetworkDNS{Split: split, Search: []string{s}, Overlay: testOverlay}
		if err := bad.validate(testMagic); err == nil {
			t.Errorf("search %q accepted", s)
		}
	}
	if ok.Empty() || ok.Key() == (NetworkDNS{Split: split, Overlay: testOverlay}).Key() {
		t.Fatal("search domains must count as settings")
	}
}

func TestNRPTScriptSearchAndCatchAll(t *testing.T) {
	n := NetworkDNS{
		Nameservers: []netip.Addr{netip.MustParseAddr("100.80.0.6")},
		Split:       []SplitDomain{{Domain: "ev.lan", Nameservers: []netip.Addr{netip.MustParseAddr("100.80.0.5")}}},
		Search:      []string{"openscale.internal"},
		CatchAll:    true,
		Overlay:     testOverlay,
	}
	script, err := nrptScript(testMagic, n)
	if err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(script, "Add-DnsClientNrptRule -Namespace '.' -NameServers '100.80.255.254'") ||
		strings.Contains(script, "'.ev.lan'") || strings.Contains(script, "-NameServers '100.80.0.6'") {
		t.Fatalf("catch-all script:\n%s", script)
	}
	if !strings.Contains(script, "-ConnectionSpecificSuffix 'openscale.internal'") {
		t.Fatalf("suffix missing:\n%s", script)
	}
	// Without network-wide resolvers catch-all would leave other names
	// unanswered: the per-domain rules are kept.
	n.Nameservers = nil
	script, _ = nrptScript(testMagic, n)
	if !strings.Contains(script, "'.ev.lan' -NameServers '100.80.0.5'") || strings.Contains(script, "-Namespace '.' ") {
		t.Fatalf("script:\n%s", script)
	}
}
