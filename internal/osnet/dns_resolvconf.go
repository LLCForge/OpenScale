// Linux DNS managers (F-060, ADR-0034). The pure parts live here so they
// are tested on every system; dns_linux.go applies them.

// DNSBackend names how a Linux system's resolver is configured.
type DNSBackend string

const (
	// BackendResolved is systemd-resolved: per-link servers and routing
	// domains, so only the network's names go to MagicDNS.
	BackendResolved DNSBackend = "systemd-resolved"
	// BackendResolvconf is Debian's resolvconf or openresolv: an interface
	// record merged into /etc/resolv.conf.
	BackendResolvconf DNSBackend = "resolvconf"
	// BackendNetworkManager is a /etc/resolv.conf written by
	// NetworkManager itself; OpenScale writes the file and repairs it when
	// NetworkManager rewrites it (F-061).
	BackendNetworkManager DNSBackend = "networkmanager"
	// BackendFile is a plain /etc/resolv.conf, backed up and restored.
	BackendFile DNSBackend = "file"
	// BackendNRPT is Windows' Name Resolution Policy Table.
	BackendNRPT DNSBackend = "nrpt"
)

const (
	resolvConfPath = "/etc/resolv.conf"
	// resolvConfBackup keeps the original file while the tunnel runs, and
	// resolvConfLinkBackup the original symlink target, if it was one.
	resolvConfBackup     = "/etc/resolv.conf.openscale-orig"
	resolvConfLinkBackup = "/etc/resolv.conf.openscale-link"
	// resolvConfMarker starts the file OpenScale writes, so it is
	// recognised after a crash and never backed up as the original.
	resolvConfMarker = "# OpenScale: managed while the tunnel runs"
	// glibc reads at most three nameservers.
	maxResolvNameservers = 3
	// resolvconfRecord is the resolvconf interface record. Debian's
	// interface-order puts "tun*" records before the network interfaces,
	// so MagicDNS is asked first.
	resolvconfRecord = "tun.openscale"
)

// dnsEnv is what backend detection looks at.
type dnsEnv struct {
	resolvConf     []byte
	resolvConfLink string // symlink target, "" for a regular file
	hasResolvectl  bool
	hasResolvconf  bool
	nsswitch       []byte
}

// detectBackend picks the manager that owns name resolution: resolved
// when it is in use (its stub in resolv.conf or nss-resolve), then
// resolvconf when it generates the file, then NetworkManager's own file,
// and the plain file otherwise.
func detectBackend(env dnsEnv) DNSBackend {
	conf := string(env.resolvConf)
	if env.hasResolvectl && (strings.Contains(env.resolvConfLink, "/run/systemd/resolve/") ||
		hasNameserver(env.resolvConf, netip.MustParseAddr("127.0.0.53")) || nsswitchResolve(env.nsswitch)) {
		return BackendResolved
	}
	if env.hasResolvconf && (strings.Contains(env.resolvConfLink, "resolvconf") || strings.Contains(firstLines(conf, 3), "resolvconf")) {
		return BackendResolvconf
	}
	if strings.Contains(env.resolvConfLink, "NetworkManager") || strings.Contains(firstLines(conf, 3), "Generated by NetworkManager") {
		return BackendNetworkManager
	}
	return BackendFile
}

func firstLines(s string, n int) string {
	lines := strings.SplitN(s, "\n", n+1)
	return strings.Join(lines[:min(n, len(lines))], "\n")
}

// nsswitchResolve reports whether the hosts line uses nss-resolve, which
// asks systemd-resolved directly even with a static resolv.conf.
func nsswitchResolve(data []byte) bool {
	s := bufio.NewScanner(bytes.NewReader(data))
	for s.Scan() {
		line, _, _ := strings.Cut(s.Text(), "#")
		fields := strings.Fields(line)
		if len(fields) > 1 && fields[0] == "hosts:" {
			return slices.Contains(fields[1:], "resolve")
		}
	}
	return false
}

// resolvConf is the part of a resolv.conf OpenScale keeps.
type resolvConf struct {
	nameservers []netip.Addr
	search      []string
	options     []string
	managed     bool
}

func parseResolvConfFile(data []byte) resolvConf {
	var rc resolvConf
	rc.managed = bytes.HasPrefix(data, []byte(resolvConfMarker))
	s := bufio.NewScanner(bytes.NewReader(data))
	for s.Scan() {
		line := strings.TrimSpace(s.Text())
		if line == "" || line[0] == '#' || line[0] == ';' {
			continue
		}
		fields := strings.Fields(line)
		switch fields[0] {
		case "nameserver":
			if len(fields) > 1 {
				if a, err := netip.ParseAddr(fields[1]); err == nil {
					rc.nameservers = append(rc.nameservers, a)
				}
			}
		case "search", "domain":
			// The last search or domain line wins (resolv.conf(5)).
			rc.search = append([]string(nil), fields[1:]...)
		case "options":
			rc.options = append(rc.options, fields[1:]...)
		}
	}
	return rc
}

func hasNameserver(data []byte, a netip.Addr) bool {
	return slices.Contains(parseResolvConfFile(data).nameservers, a)
}

// managedResolvConf builds the resolv.conf used while the tunnel runs:
// MagicDNS first, then the original resolvers. MagicDNS answers its own
// names and refuses the rest, so the C library asks the next server for
// them. "rotate" is dropped: it would send MagicDNS names to the other
// servers.
func managedResolvConf(orig []byte, magic netip.Addr, search []string) []byte {
	rc := parseResolvConfFile(orig)
	var b strings.Builder
	b.WriteString(resolvConfMarker + "; the original is restored when it stops.\n")
	b.WriteString("nameserver " + magic.String() + "\n")
	n := 1
	for _, a := range rc.nameservers {
		if a == magic || n >= maxResolvNameservers {
			continue
		}
		b.WriteString("nameserver " + a.String() + "\n")
		n++
	}
	all := append(slices.Clone(search), rc.search...)
	all = slices.Compact(dedupe(all))
	if len(all) > 0 {
		b.WriteString("search " + strings.Join(all, " ") + "\n")
	}
	opts := slices.DeleteFunc(slices.Clone(rc.options), func(o string) bool { return o == "rotate" })
	if len(opts) > 0 {
		b.WriteString("options " + strings.Join(opts, " ") + "\n")
	}
	return []byte(b.String())
}

// dedupe keeps the first of every repeated entry.
func dedupe(in []string) []string {
	seen := make(map[string]bool, len(in))
	out := in[:0]
	for _, s := range in {
		if !seen[s] {
			seen[s] = true
			out = append(out, s)
		}
	}
	return out
}

// resolvconfRecordData is the record given to resolvconf.
func resolvconfRecordData(magic netip.Addr, search []string) []byte {
	out := "nameserver " + magic.String() + "\n"
	if len(search) > 0 {
		out += "search " + strings.Join(search, " ") + "\n"
	}
	return []byte(out)
}

// linkState is what resolvectl reports for the tunnel link.
type linkState struct {
	servers []string
	domains []string
}

// parseResolvectlList reads "Link 7 (os0): a b c" as printed by
// "resolvectl dns IFACE" and "resolvectl domain IFACE".
func parseResolvectlList(out []byte) []string {
	var items []string
	s := bufio.NewScanner(bytes.NewReader(out))
	for s.Scan() {
		_, rest, ok := strings.Cut(s.Text(), "):")
		if !ok {
			continue
		}
		items = append(items, strings.Fields(rest)...)
	}
	return items
}

// resolvedLinkPlan is what the tunnel link must hold with
// systemd-resolved: MagicDNS as its only server, the routing domains of
// the network (domain, reverse zones, split domains), "~." when every name
// goes through MagicDNS, and the search domains (a plain domain both
// searches and routes).
func resolvedLinkPlan(magic DNSConfig, n NetworkDNS) linkState {
	var v4, v6 netip.Prefix
	for _, p := range n.Overlay {
		switch {
		case p.IsValid() && p.Addr().Is4() && !v4.IsValid():
			v4 = p
		case p.IsValid() && p.Addr().Is6() && !v6.IsValid():
			v6 = p
		}
	}
	domains := linkDomains(magic.Domain, v4, v6)
	for _, s := range n.Split {
		domains = append(domains, "~"+s.Domain)
	}
	if len(n.Nameservers) > 0 || n.ExitActive {
		domains = append(domains, "~.")
	}
	for _, s := range n.Search {
		// "domain" instead of "~domain": searched and still routed here.
		domains = slices.DeleteFunc(domains, func(d string) bool { return d == "~"+s })
		domains = append(domains, s)
	}
	return linkState{servers: []string{magic.Server.String()}, domains: domains}
}

// sameSet reports whether a and b hold the same entries.
func sameSet(a, b []string) bool {
	if len(a) != len(b) {
		return false
	}
	x, y := slices.Clone(a), slices.Clone(b)
	slices.Sort(x)
	slices.Sort(y)
	return slices.Equal(x, y)
}
